def _docker_tag_lines(tag_style: str, version_from: Optional[str]) -> List[str]:
    """Tag patterns passed to docker/metadata-action."""
    if tag_style == "dev":
        lines = [
            "type=sha,prefix=dev-",
            "type=raw,value=dev-latest",
            "type=semver,pattern={{version}},prefix=dev-",
            "type=semver,pattern={{major}}.{{minor}},prefix=dev-",
        ]
        if version_from is not None:
            lines.extend([
                "type=raw,value=dev-${{ steps.imgver.outputs.version }},enable=${{ steps.imgver.outputs.version != '' }}",
                "type=raw,value=dev-${{ steps.imgver.outputs.major_minor }},enable=${{ steps.imgver.outputs.major_minor != '' }}",
            ])
        lines.extend([
            "type=raw,value=dev-${{ steps.ver.outputs.version }},enable=${{ steps.ver.outputs.version != '' }}",
            "type=raw,value=dev-${{ steps.ver.outputs.major_minor }},enable=${{ steps.ver.outputs.major_minor != '' }}",
        ])
        return lines

    # standard
    lines = [
        "type=sha",
        "type=raw,value=latest,enable={{is_default_branch}}",
        "type=semver,pattern={{version}}",
        "type=semver,pattern={{major}}.{{minor}}",
    ]
    if version_from is not None:
        lines.extend([
            "type=raw,value=${{ steps.imgver.outputs.version }},enable=${{ steps.imgver.outputs.version != '' }}",
            "type=raw,value=${{ steps.imgver.outputs.major_minor }},enable=${{ steps.imgver.outputs.major_minor != '' }}",
        ])
    lines.extend([
        "type=raw,value=${{ steps.ver.outputs.version }},enable=${{ steps.ver.outputs.version != '' }}",
        "type=raw,value=${{ steps.ver.outputs.major_minor }},enable=${{ steps.ver.outputs.major_minor != '' }}",
        "type=raw,value=latest,enable=${{ steps.ver.outputs.version != '' }}",
    ])
    return lines


def _docker_meta_step(
    image_name: str,
    docker_cfg,
    tag_style: str,
    version_from: Optional[str],
    indent: str = "      ",
) -> str:
    """Generate docker/metadata-action step + tag patterns."""
    refs = _docker_image_refs(docker_cfg, image_name)
    images_lines = "\n".join(f"{indent}      {r}" for r in refs)
    tag_lines = _docker_tag_lines(tag_style, version_from)
    tags_block = "\n".join(f"{indent}      {t}" for t in tag_lines)
    flavor = ""
    if tag_style == "dev":
        flavor = f"""{indent}    flavor: |
{indent}      latest=false
"""

    return f"""{indent}- name: Docker metadata
{indent}  id: meta
{indent}  uses: {DOCKER_META}
{indent}  with:
{indent}    images: |
{images_lines}
{indent}    tags: |
{tags_block}
{flavor}"""


def _docker_parent_job_id(parent_node) -> str:
    """Parent's merge job in native mode, build job in qemu mode."""
    if parent_node.strategy == "native":
        return f"merge-{parent_node.name}"
    return f"build-{parent_node.name}"


def _docker_build_args(
    node,
    parent_node,
    docker_cfg,
    indent: str = "      ",
) -> str:
    """Cascade BASE_IMAGE build-arg block, or empty when no parent."""
    if parent_node is None:
        return ""
    parent_primary = _docker_primary_ref(docker_cfg, _image_ref_name(parent_node.image))
    parent_job = _docker_parent_job_id(parent_node)
    return f"""{indent}    build-args: |
{indent}      {node.image.base_image_arg}={parent_primary}:${{{{ needs.{parent_job}.outputs.base-tag }}}}
"""


def _qemu_build_job(
    node,
    parent_node,
    test_needs_csv: str,
    docker_cfg,
    ci: CiConfig,
    platforms_csv: str,
) -> str:
    """Single-job QEMU multi-arch build."""
    img = node.image
    needs_parts = []
    if test_needs_csv:
        needs_parts.append(test_needs_csv)
    if parent_node is not None:
        needs_parts.append(_docker_parent_job_id(parent_node))
    needs_clause = ""
    if needs_parts:
        needs_clause = f"    needs: [ {', '.join(needs_parts)} ]\n"

    login_steps = _docker_login_steps(docker_cfg)
    version_step = _version_source_step(img.version_from, ci)
    workflow_dispatch_step = (
        _workflow_dispatch_version_step()
        if ci.docker.enable_workflow_dispatch_version
        else ""
    )
    meta_step = _docker_meta_step(
        _image_ref_name(img), docker_cfg, img.tag_style, img.version_from
    )
    build_args = _docker_build_args(node, parent_node, docker_cfg)

    return f"""  build-{img.name}:
    name: Build {img.name} (QEMU multi-arch)
    runs-on: ubuntu-latest
{needs_clause}    permissions:
      contents: read
      packages: write
    outputs:
      base-tag: ${{{{ steps.meta.outputs.version }}}}
    steps:
      - uses: {CHECKOUT}

      - uses: {DOCKER_QEMU}

      - uses: {DOCKER_BUILDX}

{login_steps}{version_step}{workflow_dispatch_step}{meta_step}
      - name: Build and push
        uses: {DOCKER_BUILD_PUSH}
        with:
          context: {img.context}
          file: {img.dockerfile}
          platforms: {platforms_csv}
          push: ${{{{ github.event_name != 'pull_request' }}}}
          tags: ${{{{ steps.meta.outputs.tags }}}}
          labels: ${{{{ steps.meta.outputs.labels }}}}
{build_args}          cache-from: type=gha
          cache-to: type=gha,mode=max
"""


def _native_per_platform_job(
    node,
    parent_node,
    test_needs_csv: str,
    docker_cfg,
    platform: str,
    runner: str,
) -> str:
    """One per-platform native job that pushes by digest."""
    img = node.image
    slug = _platform_slug(platform)
    primary = _docker_primary_ref(docker_cfg, _image_ref_name(img))
    needs_parts = []
    if test_needs_csv:
        needs_parts.append(test_needs_csv)
    if parent_node is not None:
        needs_parts.append(_docker_parent_job_id(parent_node))
    needs_clause = ""
    if needs_parts:
        needs_clause = f"    needs: [ {', '.join(needs_parts)} ]\n"

    login_steps = _docker_login_steps(docker_cfg)
    build_args = _docker_build_args(node, parent_node, docker_cfg)

    return f"""  build-{img.name}-{slug}:
    name: Build {img.name} ({platform})
    runs-on: {runner}
{needs_clause}    permissions:
      contents: read
      packages: write
    outputs:
      digest: ${{{{ steps.build.outputs.digest }}}}
    steps:
      - uses: {CHECKOUT}

      - uses: {DOCKER_BUILDX}

{login_steps}      - name: Build and push by digest
        id: build
        uses: {DOCKER_BUILD_PUSH}
        with:
          context: {img.context}
          file: {img.dockerfile}
          platforms: {platform}
          outputs: type=image,name={primary},push-by-digest=true,name-canonical=true,push=true
{build_args}          cache-from: type=gha
          cache-to: type=gha,mode=max
"""


def _native_merge_job(
    node,
    docker_cfg,
    ci: CiConfig,
    platforms: List[str],
) -> str:
    """Combine per-platform digests into one multi-arch manifest."""
    img = node.image
    primary = _docker_primary_ref(docker_cfg, _image_ref_name(img))
    per_plat_jobs = [f"build-{img.name}-{_platform_slug(p)}" for p in platforms]
    needs_csv = ", ".join(per_plat_jobs)

    digest_args = " \\\n            ".join(
        f"{primary}@${{{{ needs.build-{img.name}-{_platform_slug(p)}.outputs.digest }}}}"
        for p in platforms
    )

    login_steps = _docker_login_steps(docker_cfg)
    version_step = _version_source_step(img.version_from, ci)
    workflow_dispatch_step = (
        _workflow_dispatch_version_step()
        if ci.docker.enable_workflow_dispatch_version
        else ""
    )
    meta_step = _docker_meta_step(
        _image_ref_name(img), docker_cfg, img.tag_style, img.version_from
    )

    return f"""  merge-{img.name}:
    name: Merge {img.name} multi-arch manifest
    runs-on: ubuntu-latest
    needs: [ {needs_csv} ]
    permissions:
      contents: read
      packages: write
    outputs:
      base-tag: ${{{{ steps.meta.outputs.version }}}}
    steps:
      - uses: {CHECKOUT}

      - uses: {DOCKER_BUILDX}

{login_steps}{version_step}{workflow_dispatch_step}{meta_step}
      - name: Create multi-arch manifest
        env:
          DOCKER_METADATA_OUTPUT_JSON: ${{{{ steps.meta.outputs.json }}}}
        run: |
          TAGS=$(jq -cr '.tags | map("-t " + .) | join(" ")' <<< "$DOCKER_METADATA_OUTPUT_JSON")
          eval "docker buildx imagetools create $TAGS \\
            {digest_args}"
"""


_LANG_TEST_WORKFLOW = {"python": "test-python", "npm": "test-npm", "go": "test-go"}


def _workflow_is_managed(ci: CiConfig, basename: str) -> bool:
    """Whether the generator will actually emit `<basename>.yml` for this repo."""
    if ci.only_workflows and basename not in ci.only_workflows:
        return False
    return basename not in ci.skip_workflows


def _lang_projects(config: SyncConfig, lang: str) -> List[str]:
    if lang == "python":
        return _python_test_projects(config, config.ci)
    if lang == "npm":
        return _npm_projects(config)
    return _go_projects(config)


def _reusable_test_jobs(config: SyncConfig, ci: CiConfig, lang: str) -> tuple:
    """(gate job ids, job yaml) for gating a release job on `lang`'s tests.

    Prefers `uses:` against the generated test workflow so the matrix is defined
    exactly once — we generate both sides, so the filename and job id are known
    to be correct. Falls back to inlining a copy when that workflow is not
    managed for this repo, because a `uses:` pointing at a file the generator
    does not produce is a dangling reference that fails at run time.
    """
    projects = _lang_projects(config, lang)
    if not projects:
        return [], ""
    basename = _LANG_TEST_WORKFLOW[lang]
    if _workflow_is_managed(ci, basename):
        return ["tests"], f"  tests:\n    uses: ./.github/workflows/{basename}.yml\n"
    inline, ids = _inline_test_jobs(config, ci, prereqs=(lang,))
    return ids, inline


def _inline_test_jobs(config: SyncConfig, ci: CiConfig, prereqs=None) -> tuple:
    """Return (concatenated job YAML, list of job ids) for inlined test prereqs."""
    parts: List[str] = []
    ids: List[str] = []
    test_prereqs = set(ci.docker.test_prereqs if prereqs is None else prereqs)

    if "python" in test_prereqs:
        ruff_spec = _ruff_spec(config)
        closure = _python_dep_closure(config) if ci.python.install_local_deps else {}
        for p in _python_test_projects(config, ci):
            parts.append(
                _python_test_job(
                    p,
                    _project_dir(config, "python", p),
                    ci,
                    ruff_spec,
                    local_deps=[
                        (d, _project_dir(config, "python", d))
                        for d in closure.get(p, ())
                    ],
                )
            )
            ids.append(f"test-{p}")
    if "npm" in test_prereqs:
        for p in _npm_projects(config):
            parts.append(_npm_test_job(p, _project_dir(config, "typescript", p), ci))
            ids.append(f"test-{p}")
    if "go" in test_prereqs:
        go_version = _go_version(config)
        for p in _go_projects(config):
            parts.append(_go_test_job(p, _project_dir(config, "go", p), go_version, ci))
            ids.append(f"test-{p}")

    return "\n".join(parts), ids


def build_build_docker(config: SyncConfig, ci: CiConfig) -> str:
    """Render build-docker.yml.

    Returns "" when no docker.images are configured.
    """
    if config.docker.is_empty:
        return ""
    if not config.docker.ghcr and not config.docker.dockerhub:
        raise ValueError(
            "docker: at least one of `ghcr` or `dockerhub` must be set when "
            "any docker.images are configured."
        )

    order = docker_order(config)
    docker_cfg = config.docker
    ci_docker = ci.docker

    test_yaml, test_ids = _inline_test_jobs(config, ci)
    test_needs_csv = ", ".join(test_ids)

    name_to_node = {n.name: n for n in order}
    image_jobs: List[str] = []
    for node in order:
        platforms = list(node.image.platforms or ci_docker.default_platforms)
        platforms_csv = ",".join(platforms)
        parent_node = name_to_node.get(node.needs) if node.needs else None

        if node.strategy == "qemu":
            image_jobs.append(
                _qemu_build_job(
                    node, parent_node, test_needs_csv,
                    docker_cfg, ci, platforms_csv,
                )
            )
        else:  # native
            for plat in platforms:
                runner = ci_docker.platform_runners[plat]
                image_jobs.append(
                    _native_per_platform_job(
                        node, parent_node, test_needs_csv,
                        docker_cfg, plat, runner,
                    )
                )
            image_jobs.append(
                _native_merge_job(node, docker_cfg, ci, platforms)
            )

    triggers = ["push:\n    tags:\n      - 'v*.*.*'"]
    inputs_block = ""
    if ci_docker.enable_workflow_dispatch_version:
        inputs_block = """    inputs:
      version:
        description: 'Override version (e.g. 0.1.58 or v0.1.58). Empty produces sha-only tags.'
        required: false
        type: string
"""
    triggers.append("workflow_dispatch:\n" + inputs_block.rstrip())
    if ci_docker.build_on_pr:
        triggers.append("pull_request:")
    triggers_block = "\n  ".join(triggers)

    return f"""{GENERATED_HEADER}
name: Build & push Docker images

on:
  {triggers_block}

concurrency:
  group: docker-build-${{{{ github.ref }}}}
  cancel-in-progress: true

permissions:
  contents: read
  packages: write

jobs:
{test_yaml}{"".join(image_jobs)}"""


# (filename, generator) pairs in stable order.
def _proto_missing_pins(proto) -> List[str]:
    """Toolchain pins required by the enabled outputs but absent.

    A generated workflow that installs an *unpinned* compiler is worse than no
    workflow: proto artifacts embed tool versions, so CI would drift against
    developer machines and the check would fail on files nobody touched. Missing
    pins are therefore a generation-time error rather than a silent default.
    """
    tc = proto.toolchain
    missing: List[str] = []
    if proto.go is not None:
        if tc.protoc is None:
            missing.append("proto.toolchain.protoc (required by outputs.go)")
        if tc.protoc_gen_go is None:
            missing.append(
                "proto.toolchain.protoc_gen_go (required by outputs.go; set it, or "
                'declare preferred_versions.go["google.golang.org/protobuf"] to derive it)'
            )
        if proto.go.grpc and tc.protoc_gen_go_grpc is None:
            missing.append(
                "proto.toolchain.protoc_gen_go_grpc (required by outputs.go with grpc: true)"
            )
    if proto.python is not None and tc.grpcio_tools is None:
        missing.append("proto.toolchain.grpcio_tools (required by outputs.python)")
    if proto.typescript is not None and tc.proto_loader is None:
        missing.append("proto.toolchain.proto_loader (required by outputs.typescript)")
    return missing


def _proto_go_job(config: SyncConfig, ci: CiConfig) -> str:
    proto = config.proto
    tc = proto.toolchain
    plugins = [
        f"          go install google.golang.org/protobuf/cmd/protoc-gen-go@{tc.protoc_gen_go}"
    ]
    if proto.go.grpc:
        plugins.append(
            "          go install google.golang.org/grpc/cmd/protoc-gen-go-grpc"
            f"@{tc.protoc_gen_go_grpc}"
        )
    plugins_block = "\n".join(plugins)
    return f"""  proto-check-go:
    name: compile-protos --check (go)
    runs-on: ubuntu-latest
    steps:
      - uses: {CHECKOUT}

      - uses: {SETUP_GO}
        with:
          go-version: '{_go_version(config)}'
          cache: false

      - name: Install protoc
        uses: {SETUP_PROTOC}
        with:
          version: '{tc.protoc}'
          repo-token: ${{{{ secrets.GITHUB_TOKEN }}}}

      - name: Install Go proto plugins
        run: |
{plugins_block}

{_bootstrap_steps(ci)}
      - name: Verify generated Go code is up to date
        run: {_rt(ci, "compile-protos --check --lang go")}
"""


def _proto_python_job(config: SyncConfig, ci: CiConfig) -> str:
    tc = config.proto.toolchain
    # --python pins codegen to the interpreter that actually has grpcio-tools.
    # Under the uvx bootstrap repo-tools runs in uv's own ephemeral environment,
    # where grpc_tools is not importable, so defaulting to sys.executable would
    # look for the compiler in the wrong place.
    invocation = (
        'compile-protos --check --lang python --python "$(which python)"'
    )
    return f"""  proto-check-python:
    name: compile-protos --check (python)
    runs-on: ubuntu-latest
    steps:
      - uses: {CHECKOUT}

{_bootstrap_steps(ci, need_python=True)}
      - name: Install grpcio-tools
        run: pip install grpcio-tools=={tc.grpcio_tools}

      - name: Verify generated Python code is up to date
        run: {_rt(ci, invocation)}
"""


def _proto_typescript_job(config: SyncConfig, ci: CiConfig) -> str:
    # The generator binary lives in the npm package's node_modules/.bin, so the
    # same resolution the runner uses decides where `npm ci` has to run.
    pkg_dir = resolve_ts_package_dir(config.root, config.proto)
    workdir = "."
    if pkg_dir is not None:
        try:
            rel = pkg_dir.relative_to(config.root)
            workdir = str(rel).replace("\\", "/") or "."
        except ValueError:
            workdir = "."
    return f"""  proto-check-typescript:
    name: compile-protos --check (typescript)
    runs-on: ubuntu-latest
    steps:
      - uses: {CHECKOUT}

      - uses: {SETUP_NODE}
        with:
          node-version: '{ci.npm.node_version}'

      - name: Install TypeScript proto tooling
        run: npm ci
        working-directory: {workdir}

{_bootstrap_steps(ci)}
      - name: Verify generated TypeScript code is up to date
        run: {_rt(ci, "compile-protos --check --lang typescript")}
"""


def build_proto_check(config: SyncConfig, ci: CiConfig) -> str:
    """Drift check for generated protobuf/gRPC code, one job per language.

    Split per language on purpose: each job provisions only its own toolchain
    (protoc + Go plugins, or grpcio-tools, or npm), so the three run in parallel
    instead of serializing one job through every ecosystem's installer.
    """
    proto = config.proto
    if proto.is_empty:
        return ""

    missing = _proto_missing_pins(proto)
    if missing:
        raise ValueError(
            "proto-check.yml cannot be generated with unpinned tools:\n  - "
            + "\n  - ".join(missing)
            + "\nPin them, or add 'proto-check' to ci.skip_workflows to leave this "
              "workflow unmanaged."
        )

    paths: List[str] = ["versions.yaml", f"{proto.dir}/**"]
    for out in (proto.go, proto.python, proto.typescript):
        if out is not None:
            paths.append(f"{out.path}/**")

    jobs: List[str] = []
    if proto.go is not None:
        jobs.append(_proto_go_job(config, ci))
    if proto.python is not None:
        jobs.append(_proto_python_job(config, ci))
    if proto.typescript is not None:
        jobs.append(_proto_typescript_job(config, ci))

    return f"""{GENERATED_HEADER}
name: Proto Check

on:
  pull_request:
    paths:
{_format_paths_block(paths)}

concurrency:
  group: proto-check-${{{{ github.ref }}}}
  cancel-in-progress: true

permissions:
  contents: read

jobs:
{chr(10).join(jobs)}"""


