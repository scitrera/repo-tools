def render_all(config: SyncConfig) -> dict:
    """Generate every workflow; empty string means 'no projects of that language'."""
    ci = config.ci
    out = {}
    for filename, fn in WORKFLOW_GENERATORS:
        out[filename] = fn(config, ci)
    return out


